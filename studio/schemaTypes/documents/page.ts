import {defineArrayMember, defineField, defineType} from 'sanity'

export const page = defineType({
  name: 'page',
  title: 'Page',
  type: 'document',
  fields: [
    defineField({name: 'title', type: 'string', validation: (r) => r.required()}),
    defineField({
      name: 'slug',
      type: 'slug',
      description: 'Use "home" for the home page',
      options: {source: 'title'},
      validation: (r) => r.required(),
    }),
    defineField({
      name: 'body',
      type: 'array',
      description: 'Optional plain text. Pages are built from the page builder below.',
      of: [defineArrayMember({type: 'block'})],
    }),
    defineField({
      name: 'pageBuilder',
      title: 'Page builder',
      type: 'array',
      of: [
        defineArrayMember({type: 'hero'}),
        defineArrayMember({type: 'newsSection'}),
        defineArrayMember({type: 'instagramSection'}),
        defineArrayMember({type: 'waysSection'}),
        defineArrayMember({type: 'quotesSection'}),
        defineArrayMember({type: 'featureGrid'}),
        defineArrayMember({type: 'foundersSection'}),
        defineArrayMember({type: 'checklistSection'}),
        defineArrayMember({type: 'pricingSection'}),
        defineArrayMember({type: 'channelsSection'}),
        defineArrayMember({type: 'orgChartSection'}),
        defineArrayMember({type: 'memberDirectorySection'}),
        defineArrayMember({type: 'eventListSection'}),
        defineArrayMember({type: 'linkListSection'}),
        defineArrayMember({type: 'richTextSection'}),
        defineArrayMember({type: 'ctaSection'}),
      ],
    }),
    defineField({name: 'seo', type: 'seo'}),
    defineField({
      name: 'legacyUrl',
      title: 'Legacy URL',
      type: 'string',
      description: 'Path on the old site this was imported from (for redirects and QA).',
      readOnly: true,
    }),
  ],
  preview: {select: {title: 'title', subtitle: 'slug.current'}},
})
